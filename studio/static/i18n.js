export function t(lang, key, vars = {}) {
  let s = (UI[lang] && UI[lang][key]) ?? UI.en[key] ?? key;
  if (typeof s !== "string") return s;
  for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
  return s;
}
