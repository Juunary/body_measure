"""docs/benchmark-gfpack.md: GFPack++ against the sparrow records that already exist.

    python -m bench.gfpack_report

Reads out/bench/gfpack/runs/ (bench.gfpack_run) and the stored sparrow / this-study records of the 1007 mm
benchmark in out/bench/runs/. sparrow is never run here. No number in the report is typed by hand.
"""
import json
from pathlib import Path
import re
import statistics

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import Polygon as MplPolygon  # noqa: E402

from .gfpack_run import CHECKPOINT, GFPACK_COMMIT, OUT  # noqa: E402
from .instance import ROOT  # noqa: E402

DOCS = ROOT / 'docs'
FIGURES = DOCS / 'figures'
RUNS = ROOT / 'out' / 'bench' / 'runs'
ROWS_ORDER = ['zeroshot', 'random', 'lora']
LABELS = {'zeroshot': 'GFPack++ released checkpoint (dental), zero-shot',
          'random': 'Control: random poses, no model',
          'lora': 'GFPack++ + LoRA on shirt markers'}


def load(pattern, folder):
    return [json.loads(p.read_text(encoding='utf-8')) for p in sorted(folder.glob(pattern))]


def stats(records):
    ok = [r for r in records if r.get('evaluation') and r['evaluation']['valid']]
    if not ok:
        return None
    lens = [r['evaluation']['length_mm'] for r in ok]
    return {'runs': len(records), 'valid': len(ok), 'best': min(lens), 'median': statistics.median(lens), 'worst': max(lens),
            'eff': statistics.median(r['evaluation']['efficiency_pct'] for r in ok),
            'gap': min(r['evaluation']['min_distance_mm'] for r in ok),
            'wall': statistics.median(r['wall_s'] for r in ok), 'best_record': min(ok, key=lambda r: r['evaluation']['length_mm'])}


def main():
    sparrow = {b: load(f'sparrow_4rot_{b}s_r*.json', RUNS) for b in (30, 120, 300)}
    ours = {b: load(f'ours_4rot_{b}s_r*.json', RUNS) for b in (30, 120)}
    gf = {}
    for rec in load('gfpack-*.json', OUT / 'runs'):
        if rec['variant'].startswith('smoke'):
            continue
        gf.setdefault((rec['variant'], rec['settings']['samples'], rec['settings']['steps']), []).append(rec)
    area_m2 = 1.3031
    lower = 1317
    lines = [
        '# GFPack++ against sparrow, 1007 mm roll', '',
        'Research benchmark on one shirt pattern (six shapes, nine copies). It adds GFPack++ to the open-source '
        'comparison in [benchmark.md](benchmark.md): same polygons, same rules, same evaluator '
        '(`bench/evaluate.py`). **sparrow was not run again**: its rows are the stored records of that comparison. '
        'It says nothing about other garments or production markers.', '',
        'Generated by `python -m bench.gfpack_report`; no number below is typed by hand.', '',
        '## What GFPack++ is, and what had to be added', '',
        f'GFPack++ (Xue et al., ICCV 2025; code `TimHsue/GFPack-pp` at `{GFPACK_COMMIT}`) is a learned packer: a score '
        'model turns noise into poses (x, y, cos, sin) of the pieces by reverse diffusion. The released checkpoint '
        f'(`{CHECKPOINT}`) was trained on 440 dental polygons, 48 per puzzle, in a 1205-unit strip. It is conditioned on '
        'the polygons only: no roll width, no gap, no grain rule. Its own post-processing slides pieces left and '
        'down while they do not overlap and does not remove overlaps, and its rotations are continuous.', '',
        'So the pipeline here wraps the model (`bench/gfpack_infer.py`, CPU, in WSL):', '',
        '1. every polygon is grown by gap/2 + 0.1 mm, centred on its vertex mean and scaled so the usable roll width '
        '(1002.2 mm) becomes the 1205 units the model knows;',
        '2. the sampler draws N layouts (128 reverse-diffusion steps, the repository default);',
        '3. each layout is snapped to the allowed rotations 0/90/180/270, made overlap-free by a deterministic '
        'push-out that keeps every polygon inside the roll, and compacted with GFPack++\'s own `rm_spacing_all`;',
        '4. the 40 shortest layouts go through the shared evaluator; the best valid one is the result.', '',
        'Step 3 is not part of GFPack++. It is why the **control** row exists: the same steps with uniformly random '
        'poses instead of the model. The difference between the two rows is what the model contributes.', '',
        '## Setup', '',
        f'- Roll 1007 mm, gap 5 mm to neighbours and 5 mm to the selvedges; 9 copies, cut-line area {area_m2:.4f} m2, '
        f'so no marker is shorter than {lower} mm.',
        '- Grain rule of the sparrow records: every grain line along or across the roll (rotations 0/90/180/270), '
        'mirrored pairs. Same evaluator and rule for every row.',
        '- GFPack++ ran on CPU only (Intel Core Ultra 5 228V, 8 threads, in WSL). The paper reports GPU inference; '
        'that was not available here, so the wall times below are CPU times and are not the paper\'s speed.',
        '- Three runs (seeds 0-2) per row show the spread, not a statistical test.', '',
        '## Results', '',
        '| nester | samples x steps | runs (valid) | best mm | median mm | worst mm | median efficiency | min gap mm | median wall time |',
        '|---|---|---|---|---|---|---|---|---|']

    def row(name, s, samples='-'):
        if s is None:
            return f'| {name} | {samples} | no valid marker | - | - | - | - | - | - |'
        return (f"| {name} | {samples} | {s['runs']} ({s['valid']}) | {s['best']:.0f} | {s['median']:.0f} | {s['worst']:.0f} | "
                f"{s['eff']:.1f} % | {s['gap']:.2f} | {s['wall']:.0f} s |")

    table = {}
    for b in (30, 120, 300):
        table[f'sparrow {b}'] = stats(sparrow[b])
        lines.append(row(f'sparrow v0.2.0, {b} s budget (3 workers)', table[f'sparrow {b}']))
    for b in (30, 120):
        lines.append(row(f'This study, {b} s budget', stats(ours[b])))
    best_by_tag = {}
    for tag in ROWS_ORDER:
        for key in sorted(k for k in gf if k[0] == tag):
            s = stats(gf[key])
            lines.append(row(f'{LABELS[tag]}', s, f'{key[1]} x {key[2]}'))
            if s and (tag not in best_by_tag or s['median'] < best_by_tag[tag][1]['median']):
                best_by_tag[tag] = (key, s)
    lines += ['', 'Wall time of a GFPack++ row = model start, sampling, legalisation and compaction of all samples '
              '(WSL start-up included); the evaluator is not counted. sparrow and this study plan their search around a '
              'time budget; GFPack++ has none, so its cost is set by the number of samples.', '']

    sp120 = table['sparrow 120']
    findings = ['## Findings', '']
    if sp120:
        for tag, (key, s) in best_by_tag.items():
            diff = s['median'] - sp120['median']
            findings.append(f"- **{LABELS[tag]}** ({key[1]} x {key[2]}): median {s['median']:.0f} mm, "
                            f"{diff:+.0f} mm ({100 * diff / sp120['median']:+.1f} %) against sparrow at 120 s "
                            f"({sp120['median']:.0f} mm); area lower bound {lower} mm.")
    if 'zeroshot' in best_by_tag and 'random' in best_by_tag:
        z, r = best_by_tag['zeroshot'][1]['median'], best_by_tag['random'][1]['median']
        findings.append(f'- Model against control: the released checkpoint makes the marker {r - z:.0f} mm '
                        f'({100 * (r - z) / r:.1f} %) shorter than random poses through the same legaliser.')
    if 'lora' in best_by_tag and 'zeroshot' in best_by_tag:
        z, l = best_by_tag['zeroshot'][1]['median'], best_by_tag['lora'][1]['median']
        findings.append(f'- LoRA against zero-shot: {z - l:+.0f} mm ({100 * (z - l) / z:+.1f} %) in median length.')
    lines += findings + ['']

    # model diagnostics
    lines += ['## What the model itself produces', '',
              'Before legalisation, a layout drawn by the sampler overlaps itself: the median total overlap over the '
              'samples of a run, the share of layouts the push-out could make feasible, and the length quantiles of the '
              'feasible layouts (compaction included, evaluator margins excluded).', '',
              '| row | samples | median raw overlap | feasible layouts | shortest | 10 % quantile | median |', '|---|---|---|---|---|---|---|']
    for tag in ROWS_ORDER:
        for key in sorted(k for k in gf if k[0] == tag):
            recs = gf[key]
            ms = [r['model'] for r in recs]
            q = lambda name: statistics.median(m['estimate_length_quantiles'][name] for m in ms if m['estimate_length_quantiles'][name])
            lines.append(f"| {LABELS[tag]} | {key[1]} | {statistics.median(m['raw_overlap_mm2_median'] for m in ms) / 1e6:.2f} m2 | "
                         f"{statistics.median(m['feasible'] for m in ms) / key[1]:.0%} | {q('0.0'):.0f} mm | {q('0.1'):.0f} mm | {q('0.5'):.0f} mm |")
    lines.append('')

    # LoRA training
    teacher_path = OUT / 'teacher' / 'teacher_4rot_20s.json'
    meta_path = OUT / 'lora' / 'shirt_r16.json'
    log_path = OUT / 'lora_train.log'
    if teacher_path.exists() and meta_path.exists() and log_path.exists():
        teacher = json.loads(teacher_path.read_text(encoding='utf-8'))
        meta = json.loads(meta_path.read_text(encoding='utf-8'))
        val = [float(x) for x in re.findall(r'validation loss ([0-9.]+)', log_path.read_text(encoding='utf-8'))]
        effs = [e['efficiency_pct'] for e in teacher]
        lines += ['## LoRA fine-tuning', '',
                  f"- Teacher: {len(teacher)} markers made by this study's own nester (`bench/gfpack_teacher.py`, 20 s each, "
                  f"4 rotations, mirrored pairs) on shirt variants graded by +-15 % per axis; efficiency "
                  f"{min(effs):.1f}-{max(effs):.1f} %. Variants within 3 % of the benchmark size are excluded, so the "
                  'benchmark instance itself is not in the training set (neighbouring sizes of the same shirt are). '
                  'sparrow results are not used.',
                  f"- Method (`bench/gfpack_lora.py`): rank {meta['rank']} low-rank deltas on every attention and feed-forward "
                  f"weight of the transformer and on the output layer (base weights and geometry encoder frozen), the original "
                  f"denoising score-matching loss, {meta['steps']} steps, batch {meta['batch']}, learning rate {meta['lr']:g} "
                  f"with cosine decay, point reflection of whole markers as augmentation, {meta['validation_markers']} markers "
                  'held out for validation. Deltas are merged back into a plain state dict.',
                  f"- Validation loss {val[0]:.2f} before and {val[-1]:.2f} after training.", '',
                  'Reading the two tables together: the adapted model produces layouts that overlap much less before '
                  'legalisation and whose feasible layouts are shorter on average, but the shortest of 512 layouts did not '
                  'improve. The shortest layouts of the released model come from its wide, noisy distribution; the adapted '
                  'one is narrower. With three runs this is a pattern to check, not a result.', '']

    # figure
    picks = [('sparrow v0.2.0, 120 s', sp120['best_record']['evaluation'])] if sp120 else []
    for tag in ROWS_ORDER:
        if tag in best_by_tag:
            picks.append((f"{LABELS[tag]} ({best_by_tag[tag][0][1]} samples)", best_by_tag[tag][1]['best_record']['evaluation']))
    FIGURES.mkdir(parents=True, exist_ok=True)
    fig, axes = plt.subplots(len(picks), 1, figsize=(8, 2.1 * len(picks)))
    axes = [axes] if len(picks) == 1 else list(axes)
    for ax, (name, ev) in zip(axes, picks):
        # roll across the vertical axis in the report figures: x along the roll
        ev2 = {'length_mm': ev['length_mm'], 'placements': [{'contour': [[y, x] for x, y in p['contour']]} for p in ev['placements']]}
        ax.set_xlim(0, ev['length_mm'])
        ax.set_ylim(0, 1007)
        for p in ev2['placements']:
            ax.add_patch(MplPolygon(p['contour'], closed=True, fc='#9ecae1', ec='#08306b', lw=0.6))
        ax.set_aspect('equal')
        ax.set_title(f"{name}: {ev['length_mm']:.0f} mm, {ev['efficiency_pct']:.1f} %", fontsize=8)
        ax.tick_params(labelsize=6)
    fig.tight_layout()
    fig.savefig(FIGURES / 'benchmark_gfpack_markers.png', dpi=140)
    plt.close(fig)
    lines += ['## Best markers', '', '![Best marker of sparrow and of every GFPack++ row](figures/benchmark_gfpack_markers.png)', '',
              '## Caveats', '',
              '- The comparison is a pipeline (model + legaliser + compaction) against sparrow, not the model alone: '
              'the released GFPack++ output is not feasible on this problem without step 3.',
              '- The released checkpoint is dental; the LoRA rows learn from markers made by this study\'s own nester on '
              'graded variants of the same shirt (see "LoRA fine-tuning"), so they show adaptation to this garment family, not '
              'generalisation to other garments.',
              '- CPU only; GPU times from the paper are not reproduced.',
              "- The sampler runs with dropout off (`model.eval()`); the repository's evaluation script leaves it on. The effect was not measured.",
              '- GFPack++ has no time budget, so sparrow\'s 30/120/300 s rows and the sample-count rows are not equal-time pairs.', '']
    (DOCS / 'benchmark-gfpack.md').write_text('\n'.join(lines), encoding='utf-8')
    print('written', DOCS / 'benchmark-gfpack.md')


if __name__ == '__main__':
    main()
